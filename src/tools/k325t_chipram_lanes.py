#!/usr/bin/env python3
"""k325t_chipram_lanes.py IN OUT -- QMTech K325T: turn the generated, pre-loaded 384 KB chip
RAM (shadowram-no-attic.vhdl, mempacker output) into entity shadowram_lo with four byte lanes
(lane = address bits 1..0, row = address / 4), so that the VIC-IV's port B can read a 32-bit
word per cycle (dob32, the word at addressb(19..2)) besides the byte (dob).  Port A (CPU) stays
8 bit wide, one clock latency on both ports, as the original.  Each lane is three banks of 32K
rows (row bits 16..15 select): no inferred array is deeper than 32K, so Vivado never cascades
two RAMB36 (a cascaded pair once failed DRC REQP-1962, ADDR15 tied differently).

--empty: no pre-loaded content (all banks zero, written as (others => x"00")): the K325T's
HYPPO loads MEGA65.ROM from the card and needs nothing pre-loaded; the image of IN is ignored
(Makefile: K325T_CHIPRAM_PRELOAD)."""
import re
import sys

empty = "--empty" in sys.argv[3:]
src = open(sys.argv[1]).read()
m = re.search(r"constant\s+initram\s*:\s*ram_t\s*:=\s*\((.*?)\);", src, re.S)
if not m:
    sys.exit("k325t_chipram_lanes: no initram constant in %s" % sys.argv[1])
vals = re.findall(r'x"([0-9a-fA-F]{2})"', m.group(1))
size = 393216
if len(vals) < size:
    vals += ["00"] * (size - len(vals))
vals = vals[:size]
if empty:
    vals = ["00"] * size
rows = size // 4
BANK = 32768
banks = rows // BANK                                   # 3

out = []
out.append("""-- shadowram-k325t-lo.vhdl -- GENERATED by src/tools/k325t_chipram_lanes.py from
-- shadowram-no-attic.vhdl (do not edit; --empty: no pre-loaded content): the 384 KB chip RAM
-- as four byte lanes
-- (lane = address(1:0)), port A 8 bit (CPU), port B 8 bit + 32-bit word (VIC-IV).
library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use ieee.numeric_std.all;

entity shadowram_lo is
  port (ClkA : in std_logic;
        addressa : in integer range 0 to 1048575;
        wea : in std_logic;
        dia : in unsigned(7 downto 0);
        writes : out unsigned(7 downto 0);
        no_writes : out unsigned(7 downto 0);
        doa : out unsigned(7 downto 0);
        ClkB : in std_logic;
        addressb : in unsigned(19 downto 0);
        dob : out unsigned(7 downto 0);
        dob32 : out unsigned(31 downto 0)
        );
end shadowram_lo;

architecture Behavioral of shadowram_lo is
  signal write_count : unsigned(7 downto 0) := x"00";
  signal no_write_count : unsigned(7 downto 0) := x"00";
  type bank_t is array (0 to %d) of unsigned(7 downto 0);
""" % (BANK - 1))
for lane in range(4):
    lv = vals[lane::4]
    for bk in range(banks):
        part = lv[bk * BANK:(bk + 1) * BANK]
        if all(v == "00" for v in part):
            out.append("  constant init%d_%d : bank_t := (others => x\"00\");\n" % (lane, bk))
            continue
        out.append("  constant init%d_%d : bank_t := (\n" % (lane, bk))
        lines = []
        for i in range(0, BANK, 16):
            lines.append("    " + ",".join('x"%s"' % v.lower() for v in part[i:i + 16]))
        out.append(",\n".join(lines))
        out.append(");\n")
for lane in range(4):
    for bk in range(banks):
        out.append("  shared variable ram%d_%d : bank_t := init%d_%d;\n" % (lane, bk, lane, bk))
out.append("""  -- rows: the wrapper passes only addresses below 384 KB (others as 0); row bits 16..15 = bank
  signal rowa, rowb : integer range 0 to 131071 := 0;
  signal ra15, rb15 : integer range 0 to 32767 := 0;
  signal bka, bkb : integer range 0 to 3 := 0;
  signal sela, selb : unsigned(1 downto 0) := "00";
  signal bsa, bsb : integer range 0 to 3 := 0;        -- registered bank
  type q_t is array (0 to 3) of unsigned(7 downto 0);
  type qq_t is array (0 to %d) of q_t;
  signal qqa, qqb : qq_t := (others => (others => x"00"));
  signal qa, qb : q_t;
begin
  writes <= write_count;
  no_writes <= no_write_count;
  rowa <= addressa / 4;
  rowb <= to_integer(addressb(18 downto 2));
  ra15 <= rowa mod 32768; rb15 <= rowb mod 32768;
  bka <= rowa / 32768; bkb <= rowb / 32768;
""" % (banks - 1))
for lane in range(4):
    for bk in range(banks):
        out.append("""  process (ClkA) begin
    if rising_edge(ClkA) then
      if wea /= '0' and (addressa mod 4) = %d and bka = %d then
        ram%d_%d(ra15) := dia;
      end if;
      qqa(%d)(%d) <= ram%d_%d(ra15);
    end if;
  end process;
  process (ClkB) begin
    if rising_edge(ClkB) then
      qqb(%d)(%d) <= ram%d_%d(rb15);
    end if;
  end process;
""" % (lane, bk, lane, bk, bk, lane, lane, bk, bk, lane, lane, bk))
out.append("""  process (ClkA) begin
    if rising_edge(ClkA) then bsa <= bka; end if;
  end process;
  process (ClkB) begin
    if rising_edge(ClkB) then bsb <= bkb; end if;
  end process;
  lanes : for l in 0 to 3 generate
    qa(l) <= qqa(bsa)(l) when bsa < %d else x"00";
    qb(l) <= qqb(bsb)(l) when bsb < %d else x"00";
  end generate;
""" % (banks, banks))
out.append("""  process (ClkA) begin
    if rising_edge(ClkA) then
      sela <= to_unsigned(addressa mod 4, 2);
      if wea /= '0' then
        write_count <= write_count + 1;
      else
        no_write_count <= no_write_count + 1;
      end if;
    end if;
  end process;
  process (ClkB) begin
    if rising_edge(ClkB) then
      selb <= addressb(1 downto 0);
    end if;
  end process;
  doa <= qa(to_integer(sela));
  dob <= qb(to_integer(selb));
  dob32 <= qb(3) & qb(2) & qb(1) & qb(0);
end Behavioral;
""")
open(sys.argv[2], "w").write("".join(out))
